-- Admin UI accounts and their roles, read by Spring Security through DatabaseUserDetailsService

create table roles (
    id   bigint generated by default as identity primary key,
    -- Without the ROLE_ prefix, as in hasRole and spring.security.user.roles
    name varchar(50) not null unique
);

create table users (
    id       bigint generated by default as identity primary key,
    username varchar(100) not null unique,
    -- Encoded by the DelegatingPasswordEncoder, so it starts with the encoding id, e.g. {bcrypt}
    password varchar(255) not null,
    enabled  boolean      not null default true
);

create table user_roles (
    user_id bigint not null references users (id) on delete cascade,
    role_id bigint not null references roles (id) on delete cascade,
    primary key (user_id, role_id)
);

