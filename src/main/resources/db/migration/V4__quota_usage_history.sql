-- The final usage of each finished period of a user's quota, recorded by QuotaHistoryService before the counter
-- in Redis expires, and kept for quota.history.retention

create table quota_usage_history (
    id           bigint generated by default as identity primary key,
    user_id      bigint      not null references users (id) on delete cascade,
    period       varchar(10) not null check (period in ('HOURLY', 'DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
    period_start timestamptz not null,
    used         integer     not null check (used >= 0),
    -- The limit when the usage was recorded
    quota_limit  integer     not null check (quota_limit >= 0),
    -- Recording the same period again updates its row
    unique (user_id, period, period_start)
);
